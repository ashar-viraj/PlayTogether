#!/usr/bin/env bash
# Fetches the *build-time* headers (PipeWire, SPA, clang builtins) into .deps/ without sudo,
# and points cargo at them via .cargo/config.toml.
#
# Not needed if you can run:  sudo apt install libpipewire-0.3-dev libclang-dev pkg-config
# At runtime PlayTogether only needs PipeWire itself, which your desktop already runs.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEPS="$ROOT/.deps"
ARCH="$(dpkg-architecture -qDEB_HOST_MULTIARCH 2>/dev/null || gcc -print-multiarch)"

if pkg-config --exists libpipewire-0.3 2>/dev/null && ls /usr/lib/llvm-*/lib/clang/*/include/stddef.h >/dev/null 2>&1; then
  echo "System PipeWire + clang headers already installed; nothing to do."
  exit 0
fi

LLVM_VER="$(ls -d /usr/lib/llvm-* 2>/dev/null | grep -oE '[0-9]+$' | sort -n | tail -1)"
if [ -z "$LLVM_VER" ]; then
  echo "No libclang found. Install it with: sudo apt install libclang1" >&2
  exit 1
fi

rm -rf "$DEPS" && mkdir -p "$DEPS/debs" "$DEPS/root"
( cd "$DEPS/debs" && apt-get download libpipewire-0.3-dev libspa-0.2-dev "libclang-common-${LLVM_VER}-dev" )
for deb in "$DEPS"/debs/*.deb; do dpkg-deb -x "$deb" "$DEPS/root"; done

PC_DIR="$DEPS/root/usr/lib/$ARCH/pkgconfig"
sed -i "s|^prefix=.*|prefix=$DEPS/root/usr|" "$PC_DIR"/*.pc
# The dev package's unversioned .so is a relative symlink; point it at the system runtime library.
ln -sf "/usr/lib/$ARCH/libpipewire-0.3.so.0" "$DEPS/root/usr/lib/$ARCH/libpipewire-0.3.so"

RESOURCE_DIR="$(ls -d "$DEPS"/root/usr/lib/llvm-"$LLVM_VER"/lib/clang/* | head -1)"
mkdir -p "$ROOT/.cargo"
cat > "$ROOT/.cargo/config.toml" <<CFG
# Generated by scripts/bootstrap-deps.sh
[env]
PKG_CONFIG_PATH = "$PC_DIR"
LIBCLANG_PATH = "/usr/lib/llvm-$LLVM_VER/lib"
BINDGEN_EXTRA_CLANG_ARGS = "-resource-dir=$RESOURCE_DIR"
CFG

echo "Build deps ready in $DEPS. Now run: cargo run --release"
